export function createMainContentShellState({
    reactive,
    refs,
    state,
    actions,
    utils,
} = {}) {
    if (typeof reactive !== 'function') {
        throw new TypeError('createMainContentShellState requires Vue reactive factory');
    }

    const {
        isMobile,
        mobileTab,
        isSidebarOpen,
        currentDateLabel,
        viewDate,
        currentView,
        widthIcon,
        viewTransitionName,
        dayColWidth,
        isZooming,
        weekContainer,
        slotHeight,
        weekGridWrapper,
        dateTransitionName,
        currentWeekDays,
        timeSlots,
        tasksByDateMap,
        selectedTaskId,
        flashingTaskId,
        monthViewMode,
        currentMonthDays,
        flatScrolledDays,
    } = refs;

    return reactive({
        get isMobile() { return isMobile.value; },
        get mobileTab() { return mobileTab.value; },
        get isSidebarOpen() { return isSidebarOpen.value; },
        get currentDateLabel() { return currentDateLabel.value; },
        get viewDate() { return viewDate.value; },
        get currentView() { return currentView.value; },
        get widthIcon() { return widthIcon.value; },
        get viewTransitionName() { return viewTransitionName.value; },
        get dayColWidth() { return dayColWidth.value; },
        get isZooming() { return isZooming.value; },
        get weekContainer() { return weekContainer.value; },
        set weekContainer(value) { weekContainer.value = value; },
        get slotHeight() { return slotHeight.value; },
        get weekGridWrapper() { return weekGridWrapper.value; },
        set weekGridWrapper(value) { weekGridWrapper.value = value; },
        get dateTransitionName() { return dateTransitionName.value; },
        get currentWeekDays() { return currentWeekDays.value; },
        get timeSlots() { return timeSlots.value; },
        get settings() { return state.settings; },
        get tasksByDateMap() { return tasksByDateMap.value; },
        get selectedTaskId() { return selectedTaskId.value; },
        get flashingTaskId() { return flashingTaskId.value; },
        get monthViewMode() { return monthViewMode.value; },
        get currentMonthDays() { return currentMonthDays.value; },
        get flatScrolledDays() { return flatScrolledDays.value; },
        handleInfiniteScroll: actions.handleInfiniteScroll,
        onMainTouchStart: actions.onMainTouchStart,
        onMainTouchEnd: actions.onMainTouchEnd,
        onMainMouseDown: actions.onMainMouseDown,
        onMainMouseUp: actions.onMainMouseUp,
        onMainWheel: actions.onMainWheel,
        isMouseViewDrag: state.isMouseViewDrag,
        toggleSidebar: actions.toggleSidebar,
        changeDate: actions.changeDate,
        jumpToToday: actions.jumpToToday,
        isToday: actions.isToday,
        formatDate: utils.formatDate,
        switchView: actions.switchView,
        cycleDayWidth: actions.cycleDayWidth,
        clearSelection: actions.clearSelection,
        onBeforeLeave: actions.onBeforeLeave,
        onAfterLeave: actions.onAfterLeave,
        handleHeaderDoubleTap: actions.handleHeaderDoubleTap,
        dragEnterSlot: actions.dragEnterSlot,
        dragLeaveSlot: actions.dragLeaveSlot,
        dropToSchedule: actions.dropToSchedule,
        dragStart: actions.dragStart,
        handleDragEnd: actions.handleDragEnd,
        handleTouchStart: actions.handleTouchStart,
        handleTouchMove: actions.handleTouchMove,
        handleTouchEnd: actions.handleTouchEnd,
        handleTaskDblClick: actions.handleTaskDblClick,
        getOverlapCount: actions.getOverlapCount,
        isTaskGhost: actions.isTaskGhost,
        getTaskStyle: actions.getTaskStyle,
        selectTask: actions.selectTask,
        getBlockTitle: actions.getBlockTitle,
        initResize: actions.initResize,
        hasRecordingInfo: actions.hasRecordingInfo,
        initMobileResize: actions.initMobileResize,
        switchToWeek: actions.switchToWeek,
        handleMonthCellDoubleTap: actions.handleMonthCellDoubleTap,
        dropToMonth: actions.dropToMonth,
        setMonthRef: actions.setMonthRef,
    });
}
