export function createHeaderShellState({
    reactive,
    refs,
    state,
    computedState,
    actions,
} = {}) {
    if (typeof reactive !== 'function') {
        throw new TypeError('createHeaderShellState requires Vue reactive factory');
    }

    const {
        showMobileMenu,
        themeMode,
        isSyncing,
        user,
        saveStatus,
        historyIndex,
        history,
        currentSessionId,
        globalSearchQuery,
        userAvatar,
        showProfileMenu,
        tempNickname,
        authLoading,
    } = refs;

    return reactive({
        get showMobileMenu() { return showMobileMenu.value; },
        set showMobileMenu(value) { showMobileMenu.value = value; },
        get themeMode() { return themeMode.value; },
        get getThemeLabel() { return computedState.getThemeLabel.value; },
        get isSyncing() { return isSyncing.value; },
        get user() { return user.value; },
        get saveStatus() { return saveStatus.value; },
        get historyIndex() { return historyIndex.value; },
        get history() { return history.value; },
        get currentSessionName() { return computedState.currentSessionName.value; },
        get activeDropdown() { return refs.activeDropdown.value; },
        get settings() { return state.settings; },
        get currentSessionId() { return currentSessionId.value; },
        get globalSearchQuery() { return globalSearchQuery.value; },
        set globalSearchQuery(value) { globalSearchQuery.value = value; },
        get userAvatar() { return userAvatar.value; },
        get showProfileMenu() { return showProfileMenu.value; },
        get userDisplayName() { return computedState.userDisplayName.value; },
        get tempNickname() { return tempNickname.value; },
        set tempNickname(value) { tempNickname.value = value; },
        get authLoading() { return authLoading.value; },
        openSettings: actions.openSettings,
        toggleMobileMenu: actions.toggleMobileMenu,
        toggleTheme: actions.toggleTheme,
        exportCSV: actions.exportCSV,
        exportToICS: actions.exportToICS,
        exportJSON: actions.exportJSON,
        importJSON: actions.importJSON,
        openCreditModal: actions.openCreditModal,
        handleManualSync: actions.handleManualSync,
        undo: actions.undo,
        redo: actions.redo,
        toggleDropdown: actions.toggleDropdown,
        switchSession: actions.switchSession,
        handleSessionAction: actions.handleSessionAction,
        handleSearchEnter: actions.handleSearchEnter,
        handleUserBtnClick: actions.handleUserBtnClick,
        updateNickname: actions.updateNickname,
        onFileSelect: actions.onFileSelect,
        handleLogout: actions.handleLogout,
        startTour: actions.startTour,
        handleJSONFile: actions.handleJSONFile,
        handleMidiFile: actions.handleMidiFile,
    });
}
